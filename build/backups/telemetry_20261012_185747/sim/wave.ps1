# wave.ps1 - open a simulation waveform in GTKWave with the interesting signals already
# loaded, instead of dumping the user into an empty wave pane.
#
#   powershell -ExecutionPolicy Bypass -File sim\wave.ps1 -List
#   powershell -ExecutionPolicy Bypass -File sim\wave.ps1 tb_pwm_motor
#
# VCDs are produced by sim\run_oss.ps1 into build\oss\<tb>\<tb>.vcd. This script writes a
# GTKWave save file (.gtkw) next to the VCD from the signal list below, then launches
# GTKWave. The list is data in one place so it stays in sync with the testbenches.
#
# If a signal name here does not exist in the VCD, GTKWave simply omits it; it does not
# abort. Bit ranges must match the VCD exactly, e.g. duty_q[15:0] and ctrl_cnt[31:0].
#
# Pure ASCII on purpose (PowerShell 5.1 decodes .ps1 with the system ANSI codepage).
param(
  [string]$Tb,
  [switch]$List,
  [switch]$NoLaunch
)

$ErrorActionPreference = 'Stop'
$ws = Split-Path -Parent $PSScriptRoot
$outRoot = Join-Path $ws 'build\oss'

# Signals worth looking at, per testbench. @28 marks a single-bit trace, @22 a bus.
$signalMap = @{
  'tb_clock_reset' = @(
    '@28', 'tb_clock_reset.clk',
    '@28', 'tb_clock_reset.arst_n',
    '@28', 'tb_clock_reset.locked',
    '@28', 'tb_clock_reset.rst_n',
    '@28', 'tb_clock_reset.edge_check',
    '@22', 'tb_clock_reset.dut.arst_sync[1:0]',
    '@22', 'tb_clock_reset.dut.lock_sync[1:0]',
    '@22', 'tb_clock_reset.dut.stretch_cnt[15:0]'
  )
  'tb_tick_gen' = @(
    '@28', 'tb_tick_gen.u_fast.clk',
    '@28', 'tb_tick_gen.u_fast.tick_speed',
    '@28', 'tb_tick_gen.u_fast.tick_ctrl',
    '@28', 'tb_tick_gen.u_fast.tick_log',
    '@22', 'tb_tick_gen.u_fast.speed_cnt[31:0]',
    '@22', 'tb_tick_gen.u_fast.ctrl_cnt[31:0]',
    '@22', 'tb_tick_gen.u_fast.log_cnt[31:0]'
  )
  'tb_pwm_motor' = @(
    '@28', 'tb_pwm_motor.clk',
    '@28', 'tb_pwm_motor.rst_n',
    '@28', 'tb_pwm_motor.enable',
    '@28', 'tb_pwm_motor.brake',
    '@22', 'tb_pwm_motor.cmd[15:0]',
    '@28', 'tb_pwm_motor.dut.inhibit',
    '@28', 'tb_pwm_motor.in1',
    '@28', 'tb_pwm_motor.in2',
    '@28', 'tb_pwm_motor.pwm',
    '@22', 'tb_pwm_motor.dut.duty_q[15:0]',
    '@28', 'tb_pwm_motor.dut.dir_q',
    '@22', 'tb_pwm_motor.dut.hold_q[15:0]',
    '@22', 'tb_pwm_motor.dut.pwm_cnt[15:0]'
  )
  'tb_smoke_selftest' = @(
    '@28', 'tb_smoke_selftest.clk',
    '@28', 'tb_smoke_selftest.rst_n',
    '@22', 'tb_smoke_selftest.count[7:0]',
    '@28', 'tb_smoke_selftest.tick'
  )
  'tb_adc128s102_reader' = @(
    '@28', 'tb_adc128s102_reader.clk', '@28', 'tb_adc128s102_reader.cs_n',
    '@28', 'tb_adc128s102_reader.sclk', '@28', 'tb_adc128s102_reader.din',
    '@28', 'tb_adc128s102_reader.dout', '@22', 'tb_adc128s102_reader.data[11:0]',
    '@28', 'tb_adc128s102_reader.valid'
  )
  'tb_pid_fixed' = @(
    '@28', 'tb_pid_fixed.clk', '@22', 'tb_pid_fixed.target[31:0]',
    '@22', 'tb_pid_fixed.actual[31:0]', '@22', 'tb_pid_fixed.out[31:0]',
    '@28', 'tb_pid_fixed.valid'
  )
  'tb_control_core' = @(
    '@28', 'tb_control_core.clk', '@22', 'tb_control_core.state[2:0]',
    '@22', 'tb_control_core.sample[11:0]', '@22', 'tb_control_core.command_q[31:0]',
    '@22', 'tb_control_core.request_fault[3:0]'
  )
  'tb_safety_monitor' = @(
    '@28', 'tb_safety_monitor.clk', '@28', 'tb_safety_monitor.permit',
    '@28', 'tb_safety_monitor.latched', '@22', 'tb_safety_monitor.code[3:0]'
  )
  'tb_acg720_top' = @(
    '@28', 'tb_acg720_top.clk', '@28', 'tb_acg720_top.stby_fpga',
    '@28', 'tb_acg720_top.pwm_a', '@28', 'tb_acg720_top.board_adc_cs_n',
    '@28', 'tb_acg720_top.board_adc_sclk', '@28', 'tb_acg720_top.dbg_tick'
  )
}

$vcds = @(Get-ChildItem -Path $outRoot -Recurse -Filter *.vcd -File -ErrorAction SilentlyContinue |
          Sort-Object FullName)

if ($vcds.Count -eq 0) {
  Write-Host "no waveforms yet. Run: powershell -ExecutionPolicy Bypass -File sim\run_oss.ps1"
  exit 1
}

if ($List -or -not $Tb) {
  Write-Host "=== waveforms in build\oss ==="
  foreach ($v in $vcds) {
    $name = $v.BaseName
    Write-Host ("  {0,-20} {1,9:N1} KiB   {2}" -f $name, ($v.Length / 1KB), $v.FullName)
  }
  Write-Host ""
  Write-Host "open one with:  powershell -ExecutionPolicy Bypass -File sim\wave.ps1 <name>"
  exit 0
}

$vcd = $vcds | Where-Object { $_.BaseName -eq $Tb } | Select-Object -First 1
if (-not $vcd) { throw "no waveform named '$Tb'. Use -List to see what exists." }

$signals = $signalMap[$Tb]
if (-not $signals) {
  Write-Host "[warn] no signal list for '$Tb'; opening the bare VCD (wave pane will be empty)"
  $signals = @()
}

$gtkw = Join-Path $vcd.DirectoryName "$Tb.gtkw"
$dumpPath = $vcd.FullName -replace '\\', '/'
$traceCount = @($signals | Where-Object { $_ -notlike '@*' }).Count
$lines = @(
  '[*]',
  '[*] generated by sim\wave.ps1',
  '[*]',
  "[dumpfile] `"$dumpPath`"",
  '[timestart] 0',
  '[size] 1280 820',
  '[pos] -1 -1',
  '[sst_width] 240',
  '[signals_width] 220',
  '[sst_expanded] 1',
  '[sst_vpaned_height] 170'
) + $signals + @('[pattern_trace] 1', '[pattern_trace] 0')
Set-Content -LiteralPath $gtkw -Value $lines -Encoding ascii

$gtkwave = Join-Path $env:YOSYSHQ_ROOT 'bin\gtkwave.exe'
if (-not (Test-Path -LiteralPath $gtkwave)) { throw "gtkwave.exe not found at $gtkwave" }

Write-Host "waveform : $($vcd.FullName)  ($([math]::Round($vcd.Length/1KB,1)) KiB)"
Write-Host "save file: $gtkw   ($traceCount traces)"
if ($NoLaunch) { Write-Host "[NoLaunch] not starting GTKWave"; exit 0 }

# Launch detached so the shell returns; GTKWave owns its own window from here.
Start-Process -FilePath $gtkwave -ArgumentList @($gtkw) | Out-Null
Write-Host "GTKWave launched. Tip: Ctrl+Shift+F = zoom fit, Ctrl+scroll = zoom."
